import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join, resolve } from "node:path";
import { deflateRawSync } from "node:zlib";

const root = fileURLToPath(new URL("../", import.meta.url));
function bundleModule(source, imports) {
  const declared = [];
  const body = source.replace(/^import\s+\{([^}]+)\}\s+from\s+["']([^"']+)["'];?[ \t]*\r?$/gm, (_line, names, path) => {
    const requested = names.split(",").map((name) => name.trim()).filter(Boolean);
    if (!imports[path] || requested.some((name) => !imports[path].includes(name))) throw new Error(`Unsupported bundled import: ${path}`);
    return "";
  }).replace(/^export ((?:async )?(?:function|const|class) ([A-Za-z_$][\w$]*))/gm, (_line, declaration, name) => {
    declared.push(name);
    return declaration;
  });
  if (/^\s*(?:import|export)\b/m.test(body) || /\bimport\s*\(/.test(body)) throw new Error("An unresolved module statement remains in the plugin bundle.");
  if (!declared.length) throw new Error("A bundled module has no public declarations.");
  return { code: `const { ${declared.join(", ")} } = (() => {\n${body}\nreturn { ${declared.join(", ")} };\n})();`, names: declared };
}

